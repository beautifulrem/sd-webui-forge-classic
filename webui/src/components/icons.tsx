const DEFAULTS: IconProps = { weight: "bold", size: 24 }

export function IconDefaults({ children }: { children: ReactNode }) {
  return <IconContext value={DEFAULTS}>{children}</IconContext>
}

// The right-hand panel toggles: the left one's glyph, mirrored.
